import assert from "node:assert/strict";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import vm from "node:vm";

// data/result-copy.json 是唯一文字源；同步浏览器目录和可审阅的 Markdown。
const root = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
const catalog = JSON.parse(await readFile(new URL("data/result-copy.json", root), "utf8"));
const keys = new Set(catalog.dimensions.map((item) => item.key));
assert.equal(keys.size, 12);
assert.equal(catalog.examples.length, 7);
assert.equal(catalog.features.length, 19);
for (const group of [catalog.features, catalog.patterns, catalog.examples]) {
  assert.equal(new Set(group.map((item) => item.id)).size, group.length, "文案 ID 不可重复");
}
const exampleIds = new Set(catalog.examples.map((item) => item.id));
for (const feature of catalog.features) {
  assert.ok(keys.has(feature.key));
  assert.ok(["high", "low"].includes(feature.side));
  assert.ok(typeof feature.text === "string" && feature.text.endsWith("。"));
  assert.ok(typeof feature.summary === "string" && feature.summary.endsWith("。"));
}
for (const pattern of catalog.patterns) {
  assert.ok(exampleIds.has(pattern.id));
  assert.ok(pattern.conditions.length >= 4);
  for (const condition of pattern.conditions) {
    assert.ok(keys.has(condition.key));
    assert.ok(["high", "low"].includes(condition.side));
  }
}
for (const item of catalog.examples) {
  assert.equal(item.paragraphs.length, 2);
  assert.ok(item.paragraphs.every((text) => text.endsWith("。")));
  assert.ok(!/[？?]|既有|又有/u.test(item.closing));
}
const browserSource = `// Generated by scripts/build-result-copy.mjs; edit data/result-copy.json instead.\n(function (global) {\n  "use strict";\n  function freeze(value) {\n    if (value && typeof value === "object") {\n      Object.values(value).forEach(freeze);\n      Object.freeze(value);\n    }\n    return value;\n  }\n  global.ResultCopyCatalog = freeze(${JSON.stringify(catalog, null, 2)});\n})(typeof window === "undefined" ? globalThis : window);\n`;
// 文案样例按当前算法重放，防止文字已更新而分数还停留在旧版。
const context = vm.createContext({ ResultCopyCatalog: catalog });
for (const path of ["core-algorithm/algorithm-config.js", "core-algorithm/third-layer-aggregator.js",
  "core-algorithm/fourth-layer-evidence.js", "core-algorithm/fifth-layer-mechanisms.js",
  "core-algorithm/sixth-layer-integration.js", "result-copy/selector.js"]) {
  vm.runInContext(await readFile(new URL(`js/${path}`, root), "utf8"), context, { filename: path });
}
const views = catalog.examples.map((example) => {
  const normalized = { traits: {}, special: {} };
  for (const definition of catalog.dimensions) {
    const [group, key] = definition.source;
    normalized[group][key] = example.dimensions[definition.key];
  }
  const layer3 = context.HigherOrderStructure.aggregate(normalized);
  const layer4 = context.Layer4Evidence.fromLayer3(layer3);
  const layer5 = context.Layer5Mechanisms.calculate(layer4);
  const sixth = context.Layer6Integration.calculate(layer5);
  const outcome = { version: 3, status: "scored", dimensionCount: 12,
    totalScore: sixth.totalScore, stage: sixth.stage };
  const copy = context.ResultCopy.build({ outcome, layer6Integration: sixth, normalizedDimensions: normalized });
  assert.equal(copy.profileId, example.id, `样例 ${example.id} 未命中预期文案`);
  return copy;
});
const documentUrl = new URL("docs/result-copy-v1.md", root);
const original = await readFile(documentUrl, "utf8");
const start = original.indexOf("### A · 整体较稳");
const end = original.indexOf("## 6. 状态提示");
assert.ok(start >= 0 && end > start);
let index = 0;
const section = original.slice(start, end).replace(/^>.*(?:\n>.*)*/gm, (block) => {
  const example = catalog.examples[index];
  const view = views[index++];
  assert.ok(example, "文档样稿数量多于目录");
  const header = [`> **${view.scoreText}**`, ">", `> ${view.degreeText}`, ">", `> ${view.opening}`, ">"];
  return [...header,
    ...example.paragraphs.flatMap((paragraph) => [`> ${paragraph}`, ">"]),
    `> ${example.closing}`,
  ].join("\n");
});
assert.equal(index, catalog.examples.length);
let document = original.slice(0, start) + section + original.slice(end);
document = document.replace(/^\| ([A-Za-z]+\.(?:high|low)) \| ([^|]+) \| ([^|]+) \|$/gm,
  (line, id, condition) => {
    const feature = catalog.features.find((item) => item.id === id);
    assert.ok(feature, `缺少文案：${id}`);
    return `| ${id} | ${condition.trim()} | ${feature.text} |`;
  });

const outputs = [[new URL("js/result-copy/catalog.js", root), browserSource], [documentUrl, document]];
if (!check) await mkdir(new URL("js/result-copy/", root), { recursive: true });
for (const [url, expected] of outputs) {
  if (check) {
    assert.equal(await readFile(url, "utf8"), expected, `${url.pathname} 与文案源不同步`);
  } else {
    await writeFile(url, expected);
  }
}
console.log(check ? "文案源、浏览器目录和 Markdown 一致。" : "已生成文案目录并同步 Markdown。");
